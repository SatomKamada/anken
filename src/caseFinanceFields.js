// ラベルから種別を推定
function classify(label) {
  if (/率|割合|掛け率/.test(label)) return 'percent'
  if (/名|施策|ステータス|チャネル|区分|ID/.test(label)) return 'text'
  if (/期限|日時/.test(label)) return 'text'
  if (/入数|セット数|個数|残数|残日数|ヶ月目|それ以降|Total（販売）/.test(label)) return 'num'
  return 'money'
}
